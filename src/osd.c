static int glyph_index(char c)
{
	if (c >= 'A' && c <= 'Z') return c - 'A';
	if (c >= 'a' && c <= 'z') return c - 'a';
	if (c >= '0' && c <= '9') return 26 + (c - '0');
	if (c == '-')             return 36;
	return 37;
}

void diatom_osd_show(const char *text, int frames)
{
	strncpy(g_text, text, sizeof g_text - 1);
	g_text[sizeof g_text - 1] = '\0';
	g_frames_left = frames;
}

bool diatom_osd_active(void) { return g_frames_left > 0; }
void diatom_osd_tick(void)   { if (g_frames_left > 0) g_frames_left--; }

static void put(void *frame, size_t pitch, diatom_pixfmt fmt,
                int x, int y, bool on)
{
	if (fmt == DIATOM_PIX_RGB565)
		((uint16_t *)((uint8_t *)frame + (size_t)y * pitch))[x] =
			on ? 0xffff : 0x0000;
	else
		((uint32_t *)((uint8_t *)frame + (size_t)y * pitch))[x] =
			on ? 0x00ffffffu : 0x00000000u;
}

void diatom_osd_draw(void *frame, int w, int h, size_t pitch,
                     diatom_pixfmt fmt, int ox, int oy)
{
	int len, box_w, box_h, i, gx, gy, c;

	if (g_frames_left <= 0 || !frame) return;

	len   = (int)strlen(g_text);
	box_w = len * ADVANCE + PAD * 2;
	box_h = GLYPH_H + PAD * 2;
	if (ox < 0) ox = 0;
	if (oy < 0) oy = 0;
	if (ox + box_w > w || oy + box_h > h) return;   /* no room; say nothing */

	/* Solid ground first: white text alone is unreadable over bright sprites. */
	for (gy = 0; gy < box_h; gy++)
		for (gx = 0; gx < box_w; gx++)
			put(frame, pitch, fmt, ox + gx, oy + gy, false);

	for (i = 0; i < len; i++) {
		const unsigned char *g = font[glyph_index(g_text[i])];
		for (gy = 0; gy < GLYPH_H; gy++)
			for (gx = 0; gx < GLYPH_W; gx++)
				if (g[gy] & (0x10 >> gx))
					put(frame, pitch, fmt,
					    ox + PAD + i * ADVANCE + gx, oy + PAD + gy, true);
	}
	(void)c;
}
